    private CancellationTokenSource? _previewCancellation;
    private long _previewGeneration;
    private ExtractionResult? _previewSource;
    private PreviewQueryView? _previewView;
    private PreviewQueryResult? _previewQueryResult;
    private string[] _previewHeaders = Array.Empty<string>();
    private string _previewHeaderFingerprint = "";
    private PreviewColumnPreference[] _previewColumns = Array.Empty<PreviewColumnPreference>();
    private DispatcherTimer? _previewColumnSaveTimer;
    private DependencyPropertyDescriptor? _previewWidthDescriptor;
    private readonly List<DataGridColumn> _previewObservedColumns = new();
    private bool _previewWorkspaceInitialized, _previewWorkspaceDisposed, _applyingPreviewColumns;
    private bool _previewPreferencesDirty, _previewPreferenceFailureLogged;
    private bool _previewSearching;
    private PreviewTransform _previewTransform = new();
    private string _previewTransformFingerprint = "";

    private void InitializePreviewWorkspace()
    {
        if (_previewWorkspaceInitialized) return;
        _previewColumnSaveTimer = new DispatcherTimer { Interval = TimeSpan.FromMilliseconds(600) };
        _previewColumnSaveTimer.Tick += PreviewColumnSaveTimer_Tick;
        ResultGrid.AutoGeneratedColumns += ResultGrid_PreviewAutoGeneratedColumns;
        ResultGrid.ColumnReordered += ResultGrid_PreviewColumnReordered;
        ResultGrid.Sorting += ResultGrid_Sorting;
        SearchBox.ToolTip = "Rechercher un texte dans toutes les lignes du relevé, y compris les colonnes masquées. Une sélection du dashboard limite le périmètre. Les exports restent complets.";
        _previewWorkspaceInitialized = true;
    }

    private void DisposePreviewWorkspace()
    {
        if (_previewWorkspaceDisposed) return;
        CapturePreviewColumnPreferences();
        PersistPreviewColumnPreferences();
        _previewWorkspaceDisposed = true;
        _previewGeneration++;
        _previewCancellation?.Cancel();
        _previewColumnSaveTimer?.Stop();
        if (_previewColumnSaveTimer != null) _previewColumnSaveTimer.Tick -= PreviewColumnSaveTimer_Tick;
        ResultGrid.AutoGeneratedColumns -= ResultGrid_PreviewAutoGeneratedColumns;
        ResultGrid.ColumnReordered -= ResultGrid_PreviewColumnReordered;
        ResultGrid.Sorting -= ResultGrid_Sorting;
        DetachPreviewColumnObservers();
        _previewView?.Dispose(); _previewView = null;
        _previewSource = null;
    }

    private void ResetPreviewWorkspace()
    {
        _previewGeneration++;
        _previewCancellation?.Cancel();
        _filterTimer.Stop();
        CapturePreviewColumnPreferences();
        PersistPreviewColumnPreferences();
        DetachPreviewColumnObservers();
        _previewView?.Dispose(); _previewView = null;
        _previewSource = null;
        _previewQueryResult = null;
        _preview = null;
        ResultGrid.ItemsSource = null;
    }

    private void BuildPreview(bool resetDashboard = true)
    {
        if (_result == null || _closing || _previewWorkspaceDisposed) return;
        RefreshQualityWorkspace();
        _filterTimer.Stop();
        OnExtractionChanged();
        if (resetDashboard)
        {
            _dashboardPreviewRows = null;
            _dashboardPreviewLabel = "";
            ClearDashboardFilterButton.Visibility = Visibility.Collapsed;
            QueueDashboardCalculation();
        }
        MainTabs.SelectedItem = ExtractionTab;
        ApplyPreviewFilter();
    }

    /// <summary>Only a DataRow belonging to the current displayed extraction can resolve a ticket.</summary>
    private int? GetPreviewSourceIndex(DataRow row)
    {
        if (_result == null || !ReferenceEquals(_previewSource, _result) || !ReferenceEquals(row.Table, _preview)) return null;
        return _previewView?.GetSourceIndex(row, _result);
    }

    private async void ApplyPreviewFilter()
    {
        if (_closing || _previewWorkspaceDisposed) return;
        _filterTimer.Stop();
        var generation = ++_previewGeneration;
        _previewCancellation?.Cancel();
        var source = _result;
        if (source == null) return;

        CapturePreviewColumnPreferences();
        PreparePreviewColumnPreferences(source.Headers);
        if (!ReferenceEquals(_previewSource, source))
        {
            DetachPreviewColumnObservers();
            _previewView?.Dispose(); _previewView = null;
            _previewSource = null;
            _previewQueryResult = null;
            _preview = null;
            ResultGrid.ItemsSource = null;
        }

        var operation = new CancellationTokenSource();
        _previewCancellation = operation;
        var term = SearchBox.Text.Trim();
        var fingerprint = PreviewViewPreferences.Fingerprint(source.Headers);
        if (_previewTransformFingerprint != fingerprint) { _previewTransform = new(); _previewTransformFingerprint = fingerprint; }
        var transform = _previewTransform.Copy();
        var scope = _dashboardPreviewRows?.ToArray();
        var culture = _settings.Dashboard.DateCulture == "invariant" ? CultureInfo.InvariantCulture : CultureInfo.GetCultureInfo(_settings.Dashboard.DateCulture);
        StatsText.Text = term.Length == 0 ? "Préparation de l’aperçu…" : "Recherche complète en cours…";
        if (_preview == null)
        {
            EmptyStatePanel.Visibility = Visibility.Visible;
            EmptyStateTitleText.Text = "Préparation du tableau";
            EmptyStateHintText.Text = "Les correspondances sont recherchées dans toutes les lignes du périmètre.";
        }

        try
        {
            var built = await Task.Run(() => PreviewQueryService.CreateView(source, term, PreviewLimit, scope, culture, operation.Token, transform), operation.Token);
            if (operation.IsCancellationRequested || _closing || generation != _previewGeneration || !ReferenceEquals(source, _result)) { built.Dispose(); return; }
            // Capture a resize/reorder made while the worker was running before replacing the grid's columns.
            CapturePreviewColumnPreferences();
            DetachPreviewColumnObservers();
            var previousView = _previewView;
            _preview = built.Table;
            _previewView = built;
            _previewSource = source;
            _previewQueryResult = built.Query;
            _previewSearching = term.Length > 0;
            ResultGrid.ItemsSource = _preview.DefaultView;
            previousView?.Dispose();
            ApplyPreviewColumnPreferences();
            ApplyPreviewSortIndicators();
            ApplyInterfaceDensity();
            UpdatePreviewSummary(source, built.Query, term.Length > 0);
            UpdateControls();
        }
        catch (OperationCanceledException) when (operation.IsCancellationRequested) { }
        catch (Exception ex)
        {
            if (_closing || generation != _previewGeneration || !ReferenceEquals(source, _result)) return;
            StatsText.Text = "Aperçu indisponible";
            ResultSummaryText.Text = "L’aperçu n’a pas pu être actualisé. Le relevé et ses exports sont conservés. Réessayez la recherche.";
            AddLog("APERÇU · actualisation impossible (" + ex.GetType().Name + "). Les données du relevé sont conservées.");
            if (_preview == null)
            {
                EmptyStatePanel.Visibility = Visibility.Visible;
                EmptyStateTitleText.Text = "L’aperçu n’est pas disponible";
                EmptyStateHintText.Text = "Réessayez la recherche ou consultez le journal. Les exports du relevé restent disponibles.";
            }
        }
        finally
        {
            if (ReferenceEquals(_previewCancellation, operation)) _previewCancellation = null;
            operation.Dispose();
        }
    }

    private void UpdatePreviewSummary(ExtractionResult source, PreviewQueryResult query, bool searching)
    {
        var visible = _previewColumns.Count(column => column.Visible);
        var columns = visible == source.Headers.Count ? $"{visible:N0} colonnes" : $"{visible:N0}/{source.Headers.Count:N0} colonnes visibles";
        StatsText.Text = searching
            ? $"{query.MatchCount:N0} correspondances · {query.DisplayedCount:N0} affichées · {columns}"
            : query.IsLimited ? $"{query.MatchCount:N0} lignes · {query.DisplayedCount:N0} affichées · {columns}"
            : $"{query.MatchCount:N0} lignes · {columns}";
        var parts = new List<string>();
        if (!string.IsNullOrWhiteSpace(source.Status)) parts.Add(source.Status.Trim().TrimEnd('.') + ".");
        if (source.Warnings.FirstOrDefault() is { Length: > 0 } warning) parts.Add(warning);
        if (_dashboardPreviewRows != null) parts.Add($"Sélection dashboard : {_dashboardPreviewLabel} · {query.ScopeCount:N0} lignes dans ce périmètre.");
        if (searching) parts.Add($"Recherche dans les {query.ScopeCount:N0} lignes du périmètre, y compris les colonnes masquées.");
        if (_previewTransform.Filters.Count > 0) parts.Add($"{_previewTransform.Filters.Count} filtres de colonnes actifs (bouton Vues).");
        if (_previewTransform.Sorts.Count > 0) parts.Add($"{_previewTransform.Sorts.Count} niveaux de tri sur toutes les correspondances.");
        if (query.IsLimited) parts.Add($"Aperçu limité aux {query.DisplayedCount:N0} premières correspondances après filtrage et tri complets.");
        parts.Add("Le filtre et les colonnes masquées ne réduisent pas les exports du relevé.");
        ResultSummaryText.Text = string.Join(" ", parts);

        var headersMissing = source.Headers.Count == 0;
        var empty = headersMissing || query.MatchCount == 0;
        EmptyStatePanel.Visibility = empty ? Visibility.Visible : Visibility.Collapsed;
        if (!empty) return;
        EmptyStateTitleText.Text = headersMissing ? "Aucune colonne disponible" : searching ? "Aucune correspondance" : "Aucune ligne dans ce périmètre";
        EmptyStateHintText.Text = headersMissing ? "La source reçue ne contient pas d’en-têtes exploitables."
            : searching ? "Essayez un autre texte ou effacez la recherche. Le filtre du dashboard reste actif s’il a été sélectionné."
            : _dashboardPreviewRows != null ? "Cette sélection du dashboard est vide. Revenez au relevé complet pour afficher les autres lignes."
            : "Le relevé reçu ne contient aucune ligne.";
    }

    private void Grid_AutoGeneratingColumn(object? sender, DataGridAutoGeneratingColumnEventArgs e)
    {
        if (_preview?.Columns.Contains(e.PropertyName) == true) e.Column.Header = _preview.Columns[e.PropertyName]!.Caption;
        e.Column.SortMemberPath = e.PropertyName;
        e.Column.Width = new DataGridLength(PreviewViewPreferences.DefaultWidth);
        e.Column.MinWidth = PreviewViewPreferences.MinimumWidth;
        e.Column.MaxWidth = PreviewViewPreferences.MaximumWidth;
        if (e.Column is DataGridTextColumn textColumn)
            textColumn.ElementStyle = new Style(typeof(TextBlock))
            {
                Setters =
                {
                    new Setter(TextBlock.TextTrimmingProperty, TextTrimming.CharacterEllipsis),
                    new Setter(TextBlock.VerticalAlignmentProperty, VerticalAlignment.Center)
                }
            };
    }

    private void ResultGrid_PreviewAutoGeneratedColumns(object? sender, EventArgs e)
    {
        ApplyPreviewColumnPreferences();
        DetachPreviewColumnObservers();
        _previewWidthDescriptor ??= DependencyPropertyDescriptor.FromProperty(DataGridColumn.WidthProperty, typeof(DataGridColumn));
        if (_previewWidthDescriptor == null) return;
        foreach (var column in ResultGrid.Columns)
        {
            _previewWidthDescriptor.AddValueChanged(column, PreviewColumnWidthChanged);
            _previewObservedColumns.Add(column);
        }
        if (_previewWorkspaceInitialized && !_closing) UpdateControls();
    }

    private void DetachPreviewColumnObservers()
    {
        if (_previewWidthDescriptor != null)
            foreach (var column in _previewObservedColumns) _previewWidthDescriptor.RemoveValueChanged(column, PreviewColumnWidthChanged);
        _previewObservedColumns.Clear();
    }

    private void ResultGrid_PreviewColumnReordered(object? sender, DataGridColumnEventArgs e) => QueuePreviewColumnSave();
    private void PreviewColumnWidthChanged(object? sender, EventArgs e) => QueuePreviewColumnSave();

    private void QueuePreviewColumnSave()
    {
        if (_applyingPreviewColumns || _previewWorkspaceDisposed) return;
        CapturePreviewColumnPreferences();
        if (!_previewPreferencesDirty) return;
        _previewColumnSaveTimer?.Stop();
        _previewColumnSaveTimer?.Start();
    }

    private void PreviewColumnSaveTimer_Tick(object? sender, EventArgs e)
    {
        _previewColumnSaveTimer?.Stop();
        PersistPreviewColumnPreferences();
    }

    private void PreparePreviewColumnPreferences(IReadOnlyList<string> headers)
    {
        var fingerprint = PreviewViewPreferences.Fingerprint(headers);
        if (_previewHeaderFingerprint == fingerprint) return;
        PersistPreviewColumnPreferences();
        _previewHeaders = headers.ToArray();
        _previewHeaderFingerprint = fingerprint;
        _previewPreferencesDirty = false;
        try
        {
            _previewColumns = PreviewViewPreferences.Load(Path.Combine(AppPaths.DataRoot, "preview-view.json"), _previewHeaders);
            _previewPreferenceFailureLogged = false;
        }
        catch (Exception ex)
        {
            _previewColumns = PreviewViewPreferences.Defaults(headers.Count);
            LogPreviewPreferenceFailure(ex, "lecture");
        }
    }

    private void CapturePreviewColumnPreferences()
    {
        if (_applyingPreviewColumns || _preview == null || _preview.Columns.Count != _previewHeaders.Length || ResultGrid.Columns.Count == 0) return;
        var captured = _previewColumns.Select(column => column.Copy()).ToArray();
        foreach (var gridColumn in ResultGrid.Columns)
        {
            if (PreviewColumnIndex(gridColumn) is not int index || index >= captured.Length) continue;
            captured[index].Visible = gridColumn.Visibility == Visibility.Visible;
            captured[index].DisplayIndex = gridColumn.DisplayIndex;
            captured[index].AutoWidth = !gridColumn.Width.IsAbsolute;
            if (gridColumn.Width.IsAbsolute) captured[index].Width = Math.Round(gridColumn.Width.Value, 1);
        }
        captured = PreviewViewPreferences.Normalize(captured, _previewHeaders.Length);
        if (PreviewColumnsEqual(_previewColumns, captured)) return;
        _previewColumns = captured;
        _previewPreferencesDirty = true;
    }

    private void ApplyPreviewColumnPreferences()
    {
        if (_preview == null || _previewWorkspaceDisposed) return;
        _applyingPreviewColumns = true;
        try
        {
            _previewColumns = PreviewViewPreferences.Normalize(_previewColumns, _previewHeaders.Length);
            var columns = ResultGrid.Columns.Select(column => (Column: column, Index: PreviewColumnIndex(column)))
                .Where(item => item.Index.HasValue && item.Index.Value < _previewColumns.Length)
                .ToDictionary(item => item.Index!.Value, item => item.Column);
            foreach (var preference in _previewColumns.OrderBy(column => column.DisplayIndex))
            {
                if (!columns.TryGetValue(preference.SourceIndex, out var column)) continue;
                column.MinWidth = PreviewViewPreferences.MinimumWidth;
                column.MaxWidth = PreviewViewPreferences.MaximumWidth;
                column.Width = preference.AutoWidth ? DataGridLength.Auto : new DataGridLength(preference.Width);
                column.Visibility = preference.Visible ? Visibility.Visible : Visibility.Collapsed;
                if (preference.DisplayIndex < ResultGrid.Columns.Count) column.DisplayIndex = preference.DisplayIndex;
            }
        }
        finally { _applyingPreviewColumns = false; }
    }

    private void PersistPreviewColumnPreferences()
    {
        _previewColumnSaveTimer?.Stop();
        if (!_previewPreferencesDirty || _previewHeaderFingerprint.Length == 0) return;
        try
        {
            PreviewViewPreferences.Save(Path.Combine(AppPaths.DataRoot, "preview-view.json"), _previewHeaders, _previewColumns);
            _previewPreferencesDirty = false;
            _previewPreferenceFailureLogged = false;
        }
        catch (Exception ex) { LogPreviewPreferenceFailure(ex, "enregistrement"); }
    }

    private void LogPreviewPreferenceFailure(Exception error, string action)
    {
        if (_previewPreferenceFailureLogged) return;
        _previewPreferenceFailureLogged = true;
        AddLog("COLONNES · " + action + " des préférences locales impossible (" + error.GetType().Name
            + "). L’aperçu reste utilisable ; les réglages de cette session sont conservés.");
    }

    private void OpenPreviewColumns_Click(object sender, RoutedEventArgs e)
    {
        if (_closing || _result == null || _result.Headers.Count == 0) return;
        CapturePreviewColumnPreferences();
        PreparePreviewColumnPreferences(_result.Headers);
        var fingerprint = _previewHeaderFingerprint;
        var dialog = new PreviewColumnsDialog(_previewHeaders, _previewColumns);
        dialog.Completed += accepted =>
        {
            CloseInlinePanel();
            if (!accepted || dialog.Preferences == null || _closing || _result == null || fingerprint != _previewHeaderFingerprint
                || fingerprint != PreviewViewPreferences.Fingerprint(_result.Headers)) return;
            _previewColumns = PreviewViewPreferences.Normalize(dialog.Preferences, _previewHeaders.Length);
            _previewPreferencesDirty = true;
            ApplyPreviewColumnPreferences();
            PersistPreviewColumnPreferences();
            if (ReferenceEquals(_previewSource, _result) && _previewQueryResult != null)
                UpdatePreviewSummary(_result, _previewQueryResult, _previewSearching);
        };
        ShowInlinePanel(dialog);
    }

    private static int? PreviewColumnIndex(DataGridColumn column)
    {
        var name = column.SortMemberPath;
        return name.Length > 1 && name[0] == 'C' && int.TryParse(name.AsSpan(1), NumberStyles.None, CultureInfo.InvariantCulture, out var index) && index >= 0
            ? index : null;
    }

    private static bool PreviewColumnsEqual(PreviewColumnPreference[] first, PreviewColumnPreference[] second)
        => first.Length == second.Length && first.Zip(second).All(pair => pair.First.SourceIndex == pair.Second.SourceIndex
            && pair.First.DisplayIndex == pair.Second.DisplayIndex && pair.First.Visible == pair.Second.Visible
            && pair.First.AutoWidth == pair.Second.AutoWidth && pair.First.Width.Equals(pair.Second.Width));

    private void ResultGrid_Sorting(object sender, DataGridSortingEventArgs e)
    {
        e.Handled = true;
        if (_busy || _closing || _result == null || PreviewColumnIndex(e.Column) is not int column) return;
        var existing = _previewTransform.Sorts.FirstOrDefault(sort => sort.Column == column);
        var descending = existing != null && !existing.Descending;
        if ((System.Windows.Input.Keyboard.Modifiers & System.Windows.Input.ModifierKeys.Shift) == 0) _previewTransform.Sorts.Clear();
        else if (existing != null) _previewTransform.Sorts.Remove(existing);
        if (_previewTransform.Sorts.Count >= 4) { SetStatus("La vue accepte quatre niveaux de tri. Ouvrez Vues pour les réorganiser."); return; }
        var role = _dashboard?.Columns.FirstOrDefault(value => value.Index == column)?.Role;
        var type = role == "id" ? "number" : role is "created" or "updated" or "resolved" or "closed" or "due" ? "date" : "text";
        _previewTransform.Sorts.Add(new() { Column = column, Descending = descending, Type = type });
        ApplyPreviewFilter();
    }
    private void ApplyPreviewSortIndicators()
    {
        foreach (var column in ResultGrid.Columns)
        {
            var rule = _previewTransform.Sorts.FirstOrDefault(sort => sort.Column == PreviewColumnIndex(column));
            column.SortDirection = rule == null ? null : rule.Descending ? ListSortDirection.Descending : ListSortDirection.Ascending;
        }
    }
    private void OpenPreviewViews_Click(object sender, RoutedEventArgs e)
    {
        if (_busy || _closing || _result == null || _result.Headers.Count == 0) return;
        CapturePreviewColumnPreferences();
        var fingerprint = PreviewViewPreferences.Fingerprint(_result.Headers);
        var culture = _settings.Dashboard.DateCulture == "invariant" ? CultureInfo.InvariantCulture : CultureInfo.GetCultureInfo(_settings.Dashboard.DateCulture);
        var panel = new PreviewViewsView(_result.Headers, _previewTransform, SearchBox.Text, _previewColumns, culture);
        panel.Applied += view =>
        {
            if (_closing || _result == null || fingerprint != PreviewViewPreferences.Fingerprint(_result.Headers)) return;
            _previewTransform = view.Transform.Copy(); _previewTransformFingerprint = fingerprint;
            _previewColumns = PreviewViewPreferences.Normalize(view.Columns, _result.Headers.Count);
            _previewPreferencesDirty = true; ApplyPreviewColumnPreferences(); PersistPreviewColumnPreferences();
            CloseInlinePanel(); SearchBox.Text = view.Search; ApplyPreviewFilter();
        };
        ShowInlinePanel(panel);
    }
    private async void ExportPreviewView_Click(object sender, RoutedEventArgs e)
    {
        if (_busy || _closing || _result == null) return;
        var source = _result; var transform = _previewTransform.Copy(); var search = SearchBox.Text; var scope = _dashboardPreviewRows?.ToArray();
        var columns = _previewColumns.Where(column => column.Visible).OrderBy(column => column.DisplayIndex).Select(column => column.SourceIndex).ToArray();
        var culture = _settings.Dashboard.DateCulture == "invariant" ? CultureInfo.InvariantCulture : CultureInfo.GetCultureInfo(_settings.Dashboard.DateCulture);
        var dialog = new Microsoft.Win32.SaveFileDialog { Title = "Exporter toutes les lignes de cette vue", Filter = "Classeur Excel|*.xlsx|CSV|*.csv", FileName = "GLPI-Vue.xlsx" };
        if (dialog.ShowDialog(this) != true) return;
        await RunAsync("Export de la vue filtrée et triée…", async ct =>
        {
            var exported = await Task.Run(() =>
            {
                var query = PreviewQueryService.Query(source, search, 1000000, scope, ct, transform, culture);
                var data = new ExtractionResult { Headers = columns.Select(index => source.Headers[index]).ToList(),
                    Rows = query.SourceIndices.Select(index => columns.Select(column => column < source.Rows[index].Length ? source.Rows[index][column] : "").ToArray()).ToList(),
                    Title = "Vue locale", SourceUrl = source.SourceUrl, ExtractedAt = source.ExtractedAt, Complete = false,
                    Scope = "Vue filtrée et triée localement · colonnes visibles", Warnings = new() { "Sous-ensemble local du relevé. Ce fichier ne représente pas toutes les données de la recherche GLPI." } };
                return Path.GetExtension(dialog.FileName).Equals(".csv", StringComparison.OrdinalIgnoreCase) ? ExportService.WriteCsv(data, dialog.FileName, ct) : ExportService.WriteXlsx(data, dialog.FileName, ct);
            }, ct);
            RememberExport(exported.Path); SetStatus($"Vue exportée : {exported.Rows:N0} lignes et {exported.Columns:N0} colonnes.");
        });
    }

