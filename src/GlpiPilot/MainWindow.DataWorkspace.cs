{
    private readonly SelectionBasket _selectionBasket = new();
    private readonly SourceSchemaStore _schemas = new();
    private readonly LocalResultMappingStore _localMappings = new();
    private SchemaChange? _schemaChange;
    private string _schemaSource = "";
    private TextBlock? _schemaNotice;
    private void InitializeDataWorkspace()
    {
        var tools = PilotControls.Button("Données ▾", () => { }); tools.MinHeight = 32; tools.Padding = new Thickness(10, 5, 10, 5); tools.FontSize = 12;
        var menu = new ContextMenu();
        void Item(string title, Action action) { var item = new MenuItem { Header = title }; item.Click += (_, _) => { try { action(); } catch (Exception error) { ShowError(error); } }; menu.Items.Add(item); }
        Item("Correspondances, formats et valeurs", OpenMappingAssistant);
        Item("Lire la cellule complète · F2", OpenCurrentCell);
        Item("Ajouter les lignes sélectionnées au panier", () =>
        {
            if (_result == null) return;
            var rows = ResultGrid.SelectedItems.OfType<DataRowView>().Select(row => GetPreviewSourceIndex(row.Row)).Where(index => index.HasValue).Select(index => index!.Value).ToArray();
            var added = _selectionBasket.Add(_result, rows, EffectiveDashboardSettings(_settings.Dashboard));
            SetStatus($"Panier : {added} objet(s) ajouté(s), {_selectionBasket.Keys.Count} conservé(s). Les lignes sans identité stable de source ne sont pas ajoutées.");
        });
        Item("Afficher le panier dans ce relevé", () =>
        {
            if (_result == null) return; var rows = _selectionBasket.Find(_result, EffectiveDashboardSettings(_settings.Dashboard));
            ShowDashboardRows(rows, $"Panier · {rows.Length} objets retrouvés sur {_selectionBasket.Keys.Count} conservés (les absents et identifiants ambigus restent exclus)");
        });
        Item("Retirer les lignes sélectionnées du panier", () =>
        { if (_result != null) { var resolve = DataObjectIdentity.KeyResolver(_result, EffectiveDashboardSettings(_settings.Dashboard)); _selectionBasket.Remove(ResultGrid.SelectedItems.OfType<DataRowView>().Select(r => GetPreviewSourceIndex(r.Row)).Where(i => i.HasValue).Select(i => resolve(i!.Value)).ToArray()); SetStatus("Sélection retirée du panier."); } });
        Item("Vider le panier", () => { _selectionBasket.Clear(); SetStatus("Panier vidé."); });
        tools.ContextMenu = menu; tools.Click += (_, _) => { menu.PlacementTarget = tools; menu.Placement = PlacementMode.Bottom; menu.IsOpen = true; }; PreviewActions.Children.Insert(0, tools);
        _schemaNotice = PilotControls.Text("", 12, true); _schemaNotice.Visibility = Visibility.Collapsed;
        PreviewHeader.RowDefinitions.Add(new RowDefinition { Height = GridLength.Auto }); Grid.SetRow(_schemaNotice, 2); Grid.SetColumnSpan(_schemaNotice, 2); PreviewHeader.Children.Add(_schemaNotice);
        ResultGrid.PreviewKeyDown += (_, e) => { if (e.Key == Key.F2) { OpenCurrentCell(); e.Handled = true; } };
        ResultGrid.AutoGeneratedColumns += (_, _) => AddHeaderFilters();
        ResultGrid.CopyingRowClipboardContent += (_, e) =>
        {
            if (!e.IsColumnHeadersRow || _result == null) return;
            for (int i = 0; i < e.ClipboardRowContent.Count; i++)
            {
                var cell = e.ClipboardRowContent[i];
                if (PreviewColumnIndex(cell.Column) is int index && index < _result.Headers.Count)
                    e.ClipboardRowContent[i] = new DataGridClipboardCellContent(cell.Item, cell.Column, _result.Headers[index]);
            }
        };
        var cellMenu = new ContextMenu(); var read = new MenuItem { Header = "Lire la valeur brute et interprétée · F2" }; read.Click += (_, _) => OpenCurrentCell(); cellMenu.Items.Add(read); ResultGrid.ContextMenu = cellMenu;
    }
    private void ObserveSchema()
    {
        _schemaChange = null; _schemaSource = "";
        if (_schemaNotice != null) _schemaNotice.Visibility = Visibility.Collapsed;
        if (_result == null) return;
        _gridMemory.SetScope(ResultGrid, _result);
        if (_result.Provenance.SourceKind is "demo" || IsHistoricalResult) return;
        var key = SnapshotStore.SourceKey(_result); if (key.Length == 0) return;
        try
        {
            _schemaSource = key; _schemaChange = _schemas.Inspect(key, _result.Headers);
            if (_schemaNotice != null) { _schemaNotice.Text = _schemaChange.Changed ? $"Structure modifiée : {_schemaChange.Added.Length} colonne(s) ajoutée(s), {_schemaChange.Removed.Length} retirée(s). " + (_schemaChange.Reordered ? "Ordre des colonnes modifié. " : "") + "Données → Correspondances pour examiner les renommages proposés." : ""; _schemaNotice.Visibility = _schemaChange.Changed ? Visibility.Visible : Visibility.Collapsed; }
        }
        catch (Exception error) { AddLog("COLONNES · comparaison de structure indisponible : " + AppPaths.SafeError(error)); }
    }
    private void OpenMappingAssistant()
    {
        if (_busy || _closing) return;
        var source = _result; var schemaSource = _schemaSource; var activeProfile = _settings.ActiveSourceId;
        var target = SourceMappingPolicy.Resolve(source, _settings, IsHistoricalResult);
        if (target == SourceMappingTarget.Unavailable)
        {
            SetStatus("Le relevé affiché ne correspond pas à la source active vérifiée. Sélectionnez sa source puis collectez-la avant de modifier ses correspondances."); return;
        }
        var local = target == SourceMappingTarget.LocalResult;
        var readOnly = target == SourceMappingTarget.ArchiveReadOnly;
        var mappingSettings = readOnly ? _historicalDocument!.Dashboard.Copy() : local ? LocalMappingForCurrentResult() ?? new DashboardSettings() : _settings.Dashboard.Copy();
        var hint = readOnly ? "Archive en lecture seule · interprétation enregistrée avec ce relevé ; aucune modification du profil GLPI actif."
            : local ? "Appliquez ces correspondances uniquement au relevé local ouvert, pour cette session. Aucun profil GLPI n’est modifié."
            : source == null ? "Aucun relevé chargé · préparez les formats de la configuration active ; les colonnes seront proposées après la collecte."
            : "Correspondances de la recherche GLPI vérifiée affichée et de sa configuration active.";
        var view = new MappingAssistantView(source, mappingSettings, _schemaChange, readOnly, local ? "Appliquer au relevé local uniquement" : "Appliquer après vérification", hint);
        view.ApplyRequested += settings =>
        {
            try
            {
                if (_closing || !ReferenceEquals(source, _result) || SourceMappingPolicy.Resolve(source, _settings, IsHistoricalResult) != target
                    || !local && activeProfile != _settings.ActiveSourceId) throw new InvalidOperationException("La source a changé depuis l’ouverture de l’assistant. Rouvrez les correspondances du relevé souhaité.");
                if (local)
                {
                    _localMappings.Set(source!, settings);
                    if (CitySourceIsCurrent()) _localMappings.Set(_cityEnrichment!.Source, settings);
                }
                else
                {
                    var updated = _settings.Copy(); updated.Dashboard = settings.Copy(); CaptureActiveSource(updated); updated.Save(); _settings = updated;
                    if (source != null && schemaSource.Length > 0) _schemas.Accept(schemaSource, source.Headers);
                }
                CloseInlinePanel();
                if (!local) { LoadSettingsFields(); _controlCenter?.Load(_settings); }
                if (_result != null) { ObserveSchema(); QueueDashboardCalculation(); RefreshQualityWorkspace(); ApplyPreviewFilter(); }
                SetStatus(local ? "Correspondances appliquées au relevé local pour cette session. Aucun profil GLPI n’a été modifié." : "Correspondances et formats enregistrés pour la source ; valeurs d’origine conservées.");
            }
            catch (Exception error) { ShowError(error); }
        };
        ShowInlinePanel(view);
    }
    private DashboardSettings? LocalMappingForCurrentResult() => _localMappings.Get(_result)
        ?? (CitySourceIsCurrent() ? _localMappings.Get(_cityEnrichment!.Source) : null);
    private void OpenCurrentCell()
    {
        if (_result == null || ResultGrid.CurrentCell.Item is not DataRowView row || PreviewColumnIndex(ResultGrid.CurrentCell.Column) is not int column || GetPreviewSourceIndex(row.Row) is not int index || column >= _result.Rows[index].Length) return;
        var source = _result; var settings = EffectiveDashboardSettings(_settings.Dashboard); var raw = source.Rows[index][column]; var header = source.Headers[column];
        var role = DashboardService.ResolveColumns(source.Headers, settings).FirstOrDefault(c => c.Index == column)?.Role ?? "";
        var interpreted = MappingAssistantView.Interpret(raw, role, header, settings, source.ExtractedAt.Offset);
        var tabs = new TabControl();
        TextBox Box(string value) => new() { Text = value, IsReadOnly = true, AcceptsReturn = true, TextWrapping = TextWrapping.Wrap, VerticalScrollBarVisibility = ScrollBarVisibility.Auto, FontSize = 15, Padding = new Thickness(12) };
        tabs.Items.Add(new TabItem { Header = "Valeur brute", Content = Box(raw) }); tabs.Items.Add(new TabItem { Header = "Interprétation", Content = Box(interpreted) });
        var toolbar = new WrapPanel(); toolbar.Children.Add(PilotControls.Button("Copier la valeur brute", () => Clipboard.SetText(raw))); toolbar.Children.Add(PilotControls.Button("Copier l’interprétation", () => Clipboard.SetText(interpreted)));
        ShowInlinePanel(PilotControls.Page(header, $"Ligne source {index + 1} · rôle {(role.Length == 0 ? "sans correspondance" : role)} · relevé du {source.ExtractedAt.ToLocalTime():dd/MM/yyyy HH:mm}", tabs, toolbar));
    }
    private void AddHeaderFilters()
    {
        if (_result == null) return;
        foreach (var column in ResultGrid.Columns)
        {
            if (PreviewColumnIndex(column) is not int index || index >= _result.Headers.Count) continue;
            var header = _result.Headers[index]; var panel = new DockPanel();
            var filter = new Button { Content = _previewTransform.Filters.Any(f => f.Column == index) ? "● ▾" : "▾", Padding = new Thickness(3), MinWidth = 23, MinHeight = 24, Margin = new Thickness(5, 0, 0, 0), ToolTip = "Filtrer toutes les lignes par « " + header + " »" };
            filter.Click += (_, e) => { OpenHeaderFilter(index, header); e.Handled = true; }; DockPanel.SetDock(filter, Dock.Right); panel.Children.Add(filter); panel.Children.Add(new TextBlock { Text = header, VerticalAlignment = VerticalAlignment.Center }); column.Header = panel;
        }
    }
    private void OpenHeaderFilter(int column, string header)
    {
        if (_result == null || _busy) return; var source = _result; var previous = _previewTransform.Filters.FirstOrDefault(f => f.Column == column);
        var operators = new ComboBox { ItemsSource = new[] { "contains", "not-contains", "eq", "ne", "empty", "not-empty", "gt", "lt", "before", "after" }, SelectedItem = previous?.Operator ?? "contains", MinWidth = 150 };
        var value = PilotControls.Input(previous?.Value ?? ""); var panel = new StackPanel(); panel.Children.Add(PilotControls.Text("contains = contient ; eq = égal ; gt/lt = supérieur/inférieur ; before/after = avant/après. Les conditions portent sur toutes les lignes du relevé.", 12, true)); panel.Children.Add(operators); panel.Children.Add(value);
        void Apply(bool remove)
        {
            if (!ReferenceEquals(_result, source)) return; var draft = _previewTransform.Copy(); draft.Filters.RemoveAll(f => f.Column == column);
            if (!remove) draft.Filters.Add(new() { Column = column, Operator = operators.SelectedItem?.ToString() ?? "contains", Value = value.Text }); draft.Validate(source.Headers.Count); _previewTransform = draft; _previewTransformFingerprint = PreviewViewPreferences.Fingerprint(source.Headers); CloseInlinePanel(); ApplyPreviewFilter(); AddHeaderFilters();
        }
        var toolbar = new WrapPanel(); toolbar.Children.Add(PilotControls.Button("Appliquer le filtre", () => { try { Apply(false); } catch (Exception error) { ShowError(error); } })); toolbar.Children.Add(PilotControls.Button("Retirer ce filtre", () => Apply(true)));
        ShowInlinePanel(PilotControls.Page("Filtrer · " + header, "Filtre de colonne", panel, toolbar));
    }
    private void OpenOnboarding()
    {
        if (_busy || _closing) return;
        var panel = new StackPanel(); var source = PilotControls.Input(_settings.PortalUrl); var identity = PilotControls.Input(_settings.Dashboard.PersonalTechnician); var state = PilotControls.Text("", 12, true);
        panel.Children.Add(PilotControls.Text("1 · Collez l’adresse complète de la recherche GLPI, avec ses filtres.", 14, true)); panel.Children.Add(source);
        panel.Children.Add(PilotControls.Text("2 · Indiquez votre nom de technicien tel qu’il apparaît dans GLPI (facultatif).", 14, true)); panel.Children.Add(identity);
        panel.Children.Add(PilotControls.Text("3 · Lancez la première collecte, puis examinez les rôles et formats dans Données → Correspondances. Le SSO reste dans votre navigateur piloté.", 14, true)); panel.Children.Add(state);
        var toolbar = new WrapPanel();
        toolbar.Children.Add(PilotControls.Button("Enregistrer et configurer les correspondances", () =>
        {
            try { _ = TargetUrlPolicy.Validate(source.Text); _settings.PortalUrl = TargetUrlPolicy.PersistedTarget(source.Text); _settings.Dashboard.PersonalTechnician = identity.Text.Trim(); _settings.Interface.OnboardingCompleted = true; if (_settings.Sources.Count == 0) { var profile = new SourceProfile { Name = "Ma première recherche" }; profile.Capture(_settings); _settings.Sources.Add(profile); _settings.ActiveSourceId = profile.Id; } _settings.Save(); CloseInlinePanel(); LoadSettingsFields(); _controlCenter?.Load(_settings); UpdateControls(); OpenMappingAssistant(); }
            catch (Exception error) { state.Text = AppPaths.SafeError(error); }
        }));
        toolbar.Children.Add(PilotControls.Button("Explorer une démonstration", () => { _settings.Interface.OnboardingCompleted = true; _settings.Save(); CloseInlinePanel(); LoadDemo(); }));
        ShowInlinePanel(PilotControls.Page("Première utilisation", "Source → identité → correspondances → première collecte", panel, toolbar));
    }
}
