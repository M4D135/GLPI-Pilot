using System.ComponentModel;
using System.Data;
using System.IO;
using System.Runtime.CompilerServices;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Controls.Primitives;
using System.Windows.Data;
using System.Windows.Media;
using System.Windows.Threading;
using GlpiPilot.Core;

namespace GlpiPilot.UI;

/// <summary>Column layout is persisted per workspace and schema; reading position never changes the source.</summary>
public sealed class GridWorkspaceMemory : IDisposable
{
    public sealed class ColumnState { public string Key { get; set; } = ""; public int Order { get; set; } public double Width { get; set; } public bool Visible { get; set; } = true; }
    private sealed class ViewState { public string Key = ""; public string Scope = ""; public string Selected = ""; public double Vertical, Horizontal; public bool Restoring; public List<DataGridColumn> Observed = new(); public ScrollViewer? Scroll; public ScrollChangedEventHandler? ScrollHandler; }
    private sealed record Position(string Selected, double Vertical, double Horizontal);
    private sealed record TemporaryScope(string Value);
    private static readonly DependencyProperty ScopeProperty = DependencyProperty.RegisterAttached("ReadingScope", typeof(string), typeof(GridWorkspaceMemory), new PropertyMetadata(""));
    private readonly Dictionary<DataGrid, ViewState> _grids = new();
    private readonly Dictionary<string, Position> _positions = new(StringComparer.Ordinal);
    private readonly ConditionalWeakTable<ExtractionResult, TemporaryScope> _temporaryScopes = new();
    private Dictionary<string, List<ColumnState>> _layouts = new();
    private readonly string _path;
    private readonly DispatcherTimer _timer = new() { Interval = TimeSpan.FromSeconds(1) };
    private readonly DependencyPropertyDescriptor _width = DependencyPropertyDescriptor.FromProperty(DataGridColumn.WidthProperty, typeof(DataGridColumn));
    private readonly DependencyPropertyDescriptor _items = DependencyPropertyDescriptor.FromProperty(ItemsControl.ItemsSourceProperty, typeof(DataGrid));
    public GridWorkspaceMemory(string? path = null)
    {
        _path = path ?? Path.Combine(AppPaths.DataRoot, "table-layouts.json");
        try { if (File.Exists(_path) && new FileInfo(_path).Length < 2 * 1024 * 1024) _layouts = JsonSerializer.Deserialize<Dictionary<string, List<ColumnState>>>(File.ReadAllText(_path)) ?? new(); }
        catch (Exception error) when (error is IOException or JsonException or UnauthorizedAccessException) { }
        _timer.Tick += (_, _) => Save();
    }
    private static IEnumerable<DependencyObject> Walk(DependencyObject parent)
    { yield return parent; for (int i = 0; i < VisualTreeHelper.GetChildrenCount(parent); i++) foreach (var child in Walk(VisualTreeHelper.GetChild(parent, i))) yield return child; }
    private static string ColumnKey(DataGridColumn column) => column.SortMemberPath.Length > 0 ? column.SortMemberPath : column is DataGridBoundColumn bound && bound.Binding is Binding binding ? binding.Path?.Path ?? "" : column.Header?.ToString() ?? "";
    public void Attach(DependencyObject root)
    {
        var current = Walk(root).OfType<DataGrid>().ToHashSet();
        foreach (var stale in _grids.Keys.Where(grid => !grid.IsLoaded && !current.Contains(grid)).ToArray()) Detach(stale);
        foreach (var grid in current)
        {
            if (_grids.ContainsKey(grid)) continue;
            DependencyObject? parent = grid; string workspace = "", view = "";
            while (parent != null) { if (parent is UserControl control && view.Length == 0) view = control.GetType().Name; if (parent is TabItem tab) workspace = tab.Uid.Length > 0 ? tab.Uid : tab.Header?.ToString() ?? ""; parent = VisualTreeHelper.GetParent(parent); }
            var identity = workspace + "/" + view + "/" + grid.Name + "/" + string.Join("|", grid.Columns.Select(ColumnKey));
            var state = new ViewState { Key = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(identity))), Scope = (string)grid.GetValue(ScopeProperty) }; _grids[grid] = state;
            ReadPosition(state);
            grid.Loaded += OnLoaded; grid.Unloaded += OnUnloaded; grid.SelectionChanged += OnSelection; grid.ColumnReordered += OnColumns; grid.ContextMenuOpening += OnContextMenu;
            grid.AutoGeneratedColumns += OnGenerated; _items.AddValueChanged(grid, OnItemsChanged);
            ObserveColumns(grid, state);
            if (Walk(grid).OfType<ScrollViewer>().FirstOrDefault() is { } scroll) { state.Scroll = scroll; state.ScrollHandler = (_, e) => { if (!state.Restoring && grid.IsVisible) { state.Vertical = e.VerticalOffset; state.Horizontal = e.HorizontalOffset; } }; scroll.ScrollChanged += state.ScrollHandler; }
            Restore(grid);
        }
    }
    private void OnLoaded(object sender, RoutedEventArgs e) { if (sender is DataGrid grid) Restore(grid); }
    private void OnUnloaded(object sender, RoutedEventArgs e) { if (sender is DataGrid grid) Capture(grid); }
    private void OnGenerated(object? sender, EventArgs e) { if (sender is DataGrid grid && _grids.TryGetValue(grid, out var state)) { ObserveColumns(grid, state); Restore(grid); } }
    private void ObserveColumns(DataGrid grid, ViewState state)
    {
        foreach (var column in state.Observed) _width.RemoveValueChanged(column, OnWidthChanged);
        state.Observed = grid.Columns.ToList(); foreach (var column in state.Observed) _width.AddValueChanged(column, OnWidthChanged);
    }
    private void SavePosition(ViewState state)
    {
        _positions[state.Key + "/" + state.Scope] = new(state.Selected, state.Vertical, state.Horizontal);
        if (_positions.Count > 300) _positions.Remove(_positions.Keys.First());
    }
    private void ReadPosition(ViewState state)
    {
        var position = _positions.GetValueOrDefault(state.Key + "/" + state.Scope);
        state.Selected = position?.Selected ?? ""; state.Vertical = position?.Vertical ?? 0; state.Horizontal = position?.Horizontal ?? 0;
    }
    public void SetScope(DataGrid grid, string scope)
    {
        grid.SetValue(ScopeProperty, scope);
        if (!_grids.TryGetValue(grid, out var state) || state.Scope == scope) return;
        SavePosition(state); state.Scope = scope; ReadPosition(state); state.Restoring = true;
        try { grid.UnselectAll(); } finally { state.Restoring = false; }
    }
    public void SetScope(DataGrid grid, ExtractionResult source)
    {
        var scope = SnapshotStore.SourceKey(source);
        if (scope.Length == 0) scope = _temporaryScopes.GetValue(source, _ => new("local:" + Guid.NewGuid().ToString("N"))).Value;
        SetScope(grid, scope);
    }
    private void OnItemsChanged(object? sender, EventArgs e) { if (sender is DataGrid grid) grid.Dispatcher.BeginInvoke(() => RestorePosition(grid), DispatcherPriority.Loaded); }
    private void OnSelection(object sender, SelectionChangedEventArgs e)
    { if (sender is DataGrid grid && _grids.TryGetValue(grid, out var state) && !state.Restoring && grid.SelectedItem != null) state.Selected = ItemKey(grid, grid.SelectedItem); }
    private static string ItemKey(DataGrid grid, object item)
    {
        if (item is DataRowView row)
        {
            var column = row.Row.Table.Columns.Cast<DataColumn>().FirstOrDefault(c => DashboardService.Normalize(c.Caption) is "id" or "identifiant" or "ticket id");
            return column != null ? "ID:" + row.Row[column] : "ROW:" + string.Join("\u001F", row.Row.ItemArray.Take(4));
        }
        foreach (var name in new[] { "Key", "Id", "TicketId", "Name" }) if (item.GetType().GetProperty(name)?.GetValue(item) is { } value) return name + ":" + value;
        return item.ToString() ?? "";
    }
    private void OnColumns(object? sender, DataGridColumnEventArgs e) { if (sender is DataGrid grid) Capture(grid); }
    private void OnWidthChanged(object? sender, EventArgs e) { foreach (var grid in _grids.Keys.Where(g => g.Columns.Contains(sender as DataGridColumn))) Capture(grid); }
    private void Capture(DataGrid grid)
    {
        if (!_grids.TryGetValue(grid, out var state) || state.Restoring) return;
        SavePosition(state);
        if (grid.Name == "ResultGrid") return;
        _layouts[state.Key] = grid.Columns.Select(column => new ColumnState { Key = ColumnKey(column), Order = column.DisplayIndex, Width = column.Width.IsAbsolute ? column.Width.Value : 0, Visible = column.Visibility == Visibility.Visible }).ToList();
        _timer.Stop(); _timer.Start();
    }
    private void Restore(DataGrid grid)
    {
        if (!_grids.TryGetValue(grid, out var state)) return; state.Restoring = true;
        try
        {
            if (grid.Name != "ResultGrid" && _layouts.TryGetValue(state.Key, out var columns))
            {
                foreach (var value in (columns ?? new()).OrderBy(c => c.Order))
                {
                    var column = grid.Columns.FirstOrDefault(c => ColumnKey(c) == value.Key); if (column == null) continue;
                    if (double.IsFinite(value.Width) && value.Width > 0) column.Width = Math.Clamp(value.Width, 45, 1600);
                    column.DisplayIndex = Math.Clamp(value.Order, 0, grid.Columns.Count - 1); column.Visibility = value.Visible ? Visibility.Visible : Visibility.Collapsed;
                }
                if (grid.Columns.Count > 0 && grid.Columns.All(c => c.Visibility != Visibility.Visible)) grid.Columns[0].Visibility = Visibility.Visible;
            }
        }
        finally { state.Restoring = false; }
        grid.Dispatcher.BeginInvoke(() => RestorePosition(grid), DispatcherPriority.Loaded);
    }
    private void RestorePosition(DataGrid grid)
    {
        if (!_grids.TryGetValue(grid, out var state) || !grid.IsVisible) return; state.Restoring = true;
        try
        {
            if (state.Selected.Length > 0 && grid.SelectedItem == null)
            { var item = grid.Items.Cast<object>().FirstOrDefault(item => ItemKey(grid, item) == state.Selected); if (item != null) grid.SelectedItem = item; }
            var scroll = Walk(grid).OfType<ScrollViewer>().FirstOrDefault(); scroll?.ScrollToVerticalOffset(state.Vertical); scroll?.ScrollToHorizontalOffset(state.Horizontal);
        }
        finally { state.Restoring = false; }
    }
    private void OnContextMenu(object sender, ContextMenuEventArgs e)
    {
        if (sender is not DataGrid grid || grid.Name == "ResultGrid") return;
        DependencyObject? origin = e.OriginalSource as DependencyObject;
        while (origin != null && origin is not DataGridColumnHeader) origin = origin is Visual ? VisualTreeHelper.GetParent(origin) : null;
        if (origin is not DataGridColumnHeader) return;
        var menu = new ContextMenu();
        foreach (var column in grid.Columns.OrderBy(c => c.DisplayIndex))
        {
            var item = new MenuItem { Header = column.Header?.ToString() ?? ColumnKey(column), IsCheckable = true, IsChecked = column.Visibility == Visibility.Visible };
            item.Click += (_, _) => { if (!item.IsChecked && grid.Columns.Count(c => c.Visibility == Visibility.Visible) == 1) { item.IsChecked = true; return; } column.Visibility = item.IsChecked ? Visibility.Visible : Visibility.Collapsed; Capture(grid); };
            menu.Items.Add(item);
        }
        menu.PlacementTarget = grid; menu.IsOpen = true; e.Handled = true;
    }
    private void Save()
    {
        _timer.Stop();
        try { Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(_path))!); var temp = _path + ".tmp"; File.WriteAllText(temp, JsonSerializer.Serialize(_layouts.TakeLast(300).ToDictionary(p => p.Key, p => p.Value))); File.Move(temp, _path, true); }
        catch (Exception error) when (error is IOException or UnauthorizedAccessException) { AppPaths.AppendLog("TABLEAUX · présentation non mémorisée : " + AppPaths.SafeError(error)); }
    }
    public void Dispose()
    {
        foreach (var grid in _grids.Keys.ToArray()) Detach(grid);
        Save(); _grids.Clear();
    }
    private void Detach(DataGrid grid)
    {
        if (!_grids.TryGetValue(grid, out var state)) return;
        Capture(grid); grid.Loaded -= OnLoaded; grid.Unloaded -= OnUnloaded; grid.SelectionChanged -= OnSelection; grid.ColumnReordered -= OnColumns; grid.ContextMenuOpening -= OnContextMenu; grid.AutoGeneratedColumns -= OnGenerated; _items.RemoveValueChanged(grid, OnItemsChanged);
        foreach (var column in state.Observed) _width.RemoveValueChanged(column, OnWidthChanged);
        if (state.Scroll != null && state.ScrollHandler != null) state.Scroll.ScrollChanged -= state.ScrollHandler;
        _grids.Remove(grid);
    }
}
